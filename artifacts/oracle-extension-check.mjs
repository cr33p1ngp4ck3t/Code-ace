import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
import { chromiumPath } from '../scripts/browser-utils.mjs';
const base = 'http://127.0.0.1:4318';
const extension = resolve('extension');
const before = await (await fetch(`${base}/api/status`)).json();
const context = await chromium.launchPersistentContext('', { executablePath: await chromiumPath(), headless: true, viewport: { width: 1200, height: 1000 }, args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] });
const checks = [];
try {
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
  const id = new URL(worker.url()).host;
  const manifest = await worker.evaluate(() => chrome.runtime.getManifest());
  assert.match(manifest.name, /^Verifeed/);
  const popup = await context.newPage(); await popup.goto(`chrome-extension://${id}/popup.html`);
  await popup.locator('.connection summary').click(); await popup.waitForFunction(() => document.querySelector('#backend-url')?.value === 'http://127.0.0.1:4318');
  await popup.locator('#save-backend').click(); await popup.waitForFunction(() => document.querySelector('#connection-status').textContent.startsWith('Connected.'));
  await popup.locator('body').screenshot({ path: 'artifacts/oracle-extension-connection.png' });
  checks.push('Renamed extension connects to Oracle through its default tunnel address');
  const next = context.waitForEvent('page'); await popup.locator('#studio').click(); const studio = await next;
  await studio.waitForURL(`${base}/`); assert.match(await studio.title(), /Verifeed/);
  checks.push('Open review studio uses the Oracle backend');
  const feed = await context.newPage(); await feed.goto(`${base}/demo`); await feed.waitForSelector('#post-image .wrap.unknown');
  const count = context.pages().length; await feed.locator('#post-image [data-nova-host] button').click(); const draft = feed.frameLocator('[data-verifeed-panel] iframe');
  await draft.locator('#media-preview img').waitFor(); assert.equal(context.pages().length, count); assert.match(await draft.locator('#post-text').textContent(), /poster/);
  checks.push('Post review imports image media into the same-tab panel using Oracle configuration');
  const after = await (await fetch(`${base}/api/status`)).json(); assert.equal(after.remainingChecks, before.remainingChecks);
  checks.push('Connecting, scrolling, and importing a post spend no AI checks');
  await writeFile('artifacts/oracle-extension-checks.json', JSON.stringify({ checkedAt: new Date().toISOString(), backend: base, checks }, null, 2));
  for (const check of checks) console.log(`PASS ${check}`);
} finally { await context.close(); }
